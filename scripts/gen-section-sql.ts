// Writes SQL that adds one section from seed.json to the Supabase draft, placed right after
// the section before it in seed.json. Running the SQL again does nothing.
// Usage: npm run section:sql -- experience
import { readFileSync, writeFileSync } from 'node:fs';
import { sectionSchema } from '../src/data/schema.ts';

const id = process.argv[2];
if (!id) throw new Error('Pass a section id, e.g. npm run section:sql -- experience');

const seed = JSON.parse(readFileSync(new URL('../src/data/seed.json', import.meta.url), 'utf8'));
const index = seed.sections.findIndex((s: { id: string }) => s.id === id);
if (index === -1) throw new Error(`No section "${id}" in seed.json`);
sectionSchema.parse(seed.sections[index]);
const after: string | undefined = seed.sections[index - 1]?.id;

const json = JSON.stringify(seed.sections[index], null, 2);
if (json.includes('$section$')) throw new Error('The section contains "$section$", which would break the SQL quoting');

const outPath = new URL(`../supabase/add-section-${id}.sql`, import.meta.url);
writeFileSync(
  outPath,
  `-- Generated by \`npm run section:sql -- ${id}\` from src/data/seed.json. Don't edit by hand.
-- Adds the "${id}" section to the DRAFT${after ? `, right after "${after}"` : ''}. Running it again does nothing.
-- The live site only changes after you check it in /admin and press Publish.
update public.site_content
set data = jsonb_set(data, '{sections}', (
  select jsonb_agg(section order by pos)
  from (
    select section, pos::numeric as pos
    from jsonb_array_elements(data->'sections') with ordinality as existing(section, pos)
    union all
    select $section$${json}$section$::jsonb,
      coalesce((
        select pos from jsonb_array_elements(data->'sections') with ordinality as existing(section, pos)
        where section->>'id' = '${after ?? ''}'
      ), 1000000) + 0.5
  ) as ordered
))
where id = 'draft'
  and not exists (
    select 1 from jsonb_array_elements(data->'sections') as existing(section)
    where section->>'id' = '${id}'
  );
`,
);
console.log(`Wrote ${outPath.pathname}`);
