// Writes supabase/seed.sql from src/data/seed.json, validating it first.
// Usage: npm run seed:sql
import { readFileSync, writeFileSync } from 'node:fs';
import { contentSchema } from '../src/data/schema.ts';

const seedPath = new URL('../src/data/seed.json', import.meta.url);
const outPath = new URL('../supabase/seed.sql', import.meta.url);

const seed = JSON.parse(readFileSync(seedPath, 'utf8'));
contentSchema.parse(seed);

const json = JSON.stringify(seed, null, 2);
if (json.includes('$seed$')) throw new Error('seed.json contains "$seed$", which would break the SQL quoting');

writeFileSync(
  outPath,
  `-- Generated by \`npm run seed:sql\` from src/data/seed.json. Don't edit by hand.
-- Run in Supabase → SQL Editor after schema.sql. Re-running is safe: existing rows are left alone.
insert into public.site_content (id, data) values
  ('draft', $seed$${json}$seed$::jsonb),
  ('published', $seed$${json}$seed$::jsonb)
on conflict (id) do nothing;
`,
);
console.log(`Wrote ${outPath.pathname}`);
